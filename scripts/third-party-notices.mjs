// Generates THIRD-PARTY-NOTICES.md with the licenses of the dependencies shipped inside the app.
//
// Roots: the `dependencies` of apps/desktop (loaded at runtime) plus the UI dependencies that Vite bundles into the
// renderer (React, CodeMirror, xterm...), which live in `devDependencies` so they don't end up in the installer twice.
// Each root comes with everything it pulls in. Run from the repository root: `node scripts/third-party-notices.mjs`.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const desktop = join(root, 'apps', 'desktop')
const pnpm = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm'
const run = (args, cwd) => JSON.parse(execFileSync(pnpm, args, { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, shell: process.platform === 'win32' }))

const manifest = JSON.parse(readFileSync(join(desktop, 'package.json'), 'utf8'))
const bundledDev = (name) => /^(react|react-dom)$/.test(name) || /^@(codemirror|lezer|xterm)\//.test(name)
const roots = new Set([...Object.keys(manifest.dependencies ?? {}), ...Object.keys(manifest.devDependencies ?? {}).filter(bundledDev)])
roots.delete('@gearmod/contracts')

// Transitive closure from the roots, over the tree pnpm resolved.
const tree = run(['list', '--json', '--depth', 'Infinity'], desktop).find((project) => project.name === '@gearmod/desktop')
const wanted = new Set()
const visit = (name, node) => {
  const id = `${name}@${node.version}`
  if (wanted.has(id)) return
  wanted.add(id)
  for (const [child, value] of Object.entries(node.dependencies ?? {})) visit(child, value)
}
for (const group of [tree.dependencies ?? {}, tree.devDependencies ?? {}]) {
  for (const [name, node] of Object.entries(group)) if (roots.has(name)) visit(name, node)
}

const licenses = run(['licenses', 'list', '--json'], root)
const entries = []
for (const group of Object.values(licenses)) {
  for (const pkg of group) for (const version of pkg.versions) if (wanted.has(`${pkg.name}@${version}`)) entries.push({ name: pkg.name, version, license: pkg.license, path: pkg.paths?.[pkg.versions.indexOf(version)] ?? pkg.paths?.[0] })
}
// Rust crates compiled into the native MCP relay (apps/desktop/native/gearmod-mcp). Without cargo they are left out, with a warning.
const crate = join(desktop, 'native', 'gearmod-mcp', 'Cargo.toml')
try {
  const metadata = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--manifest-path', crate], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }))
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]))
  const used = new Set(), visitCrate = (id) => { if (used.has(id)) return; used.add(id); for (const dep of nodes.get(id)?.deps ?? []) if (dep.dep_kinds.some((kind) => kind.kind === null)) visitCrate(dep.pkg) }
  visitCrate(metadata.resolve.root)
  for (const pkg of metadata.packages) if (used.has(pkg.id) && pkg.id !== metadata.resolve.root) entries.push({ name: `${pkg.name} (Rust crate)`, version: pkg.version, license: pkg.license ?? 'see its repository', path: dirname(pkg.manifest_path), rust: true })
} catch (error) { console.warn(`Rust crates of the MCP relay left out (cargo metadata failed: ${error instanceof Error ? error.message.split('\n')[0] : error})`) }
entries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const licenseFile = (dir, rust = false) => {
  if (!dir || !existsSync(dir)) return ''
  // Rust crates usually ship LICENSE-MIT and LICENSE-APACHE (dual license): the MIT text is the one reproduced.
  const names = readdirSync(dir)
  const file = (rust && names.find((name) => /^licen[cs]e-mit(\.|$)/i.test(name))) || names.find((name) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name)) || (rust ? names.find((name) => /^(licen[cs]e|copying|unlicense)[-.]/i.test(name)) : undefined)
  return file ? readFileSync(join(dir, file), 'utf8').trim() : ''
}
const texts = new Map()
let body = ''
for (const entry of entries) {
  const text = licenseFile(entry.path, entry.rust)
  const key = text ? createHash('sha256').update(text).digest('hex').slice(0, 12) : ''
  if (text && !texts.has(key)) texts.set(key, text)
  body += `- **${entry.name}** ${entry.version} — ${entry.license}${key ? ` (text ${key})` : ' (no license file in the package; see its repository)'}\n`
}

let out = '# Third-party notices\n\nGearMod includes the open source packages below. Each one is distributed under its own license; GearMod itself is under the PolyForm Shield License 1.0.0 (see `LICENSE.md`).\n\n'
out += `Generated by \`scripts/third-party-notices.mjs\` — ${entries.length} packages.\n\n## Packages\n\n${body}\n## License texts\n\n`
for (const [key, text] of texts) out += `### Text ${key}\n\n\`\`\`text\n${text}\n\`\`\`\n\n`
writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), out)
console.log(`THIRD-PARTY-NOTICES.md: ${entries.length} packages, ${texts.size} license texts`)
